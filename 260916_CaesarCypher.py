#MAKETRANS
#The str.maketrans() method takes two strings of equal 
#length and returns a translation table that maps each character 
#of the first string with the corresponding character of the second 
#string. Each character in the translation table is stored as 
#a Unicode ordinal, a number that uniquely identifies the character.

lower_chars = 'abc'
upper_chars = 'ABC'

table = str.maketrans(lower_chars, upper_chars)
print(table) # {97: 65, 98: 66, 99: 67}

