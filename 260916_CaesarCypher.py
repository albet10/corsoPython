    upper_alphabet = alphabet.upper()
    total_alphabet = alphabet + upper_alphabet
    shifted_alphabet = alphabet[shift:] + alphabet[:shift]
    shifted_alphabet_upper = (shifted_alphabet.upper())
    upper_shifted_alphabet = shifted_alphabet + shifted_alphabet_upper
    
    
    
